// Builds simple-site/js/data.js from the curated, PubMed-sourced JSON in /content.
// Run with:  node scripts/build-simple-data.mjs
// The simple site never invents numbers: it only re-packages what /content already holds.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const THORACIC = ["nsclc", "sclc", "thymic", "mesothelioma"];
const read = (f) => JSON.parse(fs.readFileSync(f, "utf8"));
const list = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => read(path.join(dir, f))) : []);

const trials = THORACIC.flatMap((d) => list(path.join(root, "content/trials", d))).map((t) => ({
  slug: t.slug,
  acronym: t.acronym,
  title: t.officialTitle,
  disease: t.disease,
  setting: t.setting,
  stages: t.stages,
  classes: t.treatmentClasses,
  biomarkers: t.biomarkers,
  phase: t.phase,
  year: t.yearOfPrimaryPublication,
  result: t.result,
  landmark: t.landmark,
  question: t.clinicalQuestion,
  pico: t.pico,
  design: t.design,
  arms: t.arms,
  registry: t.registryIds,
  publications: t.publications.map((p) => ({ pmid: p.pmid, doi: p.doi, title: p.title, journal: p.journal, year: p.year, author: p.firstAuthor, type: p.type, label: p.label })),
  outcomes: t.outcomes,
  safety: t.safety,
  strengths: t.appraisal?.strengths ?? [],
  limitations: t.appraisal?.limitations ?? [],
  implications: t.clinicalImplications?.text,
  pearl: t.tumourBoardPearl?.text,
  status: t.evidenceStatus,
}));

const biomarkers = list(path.join(root, "content/biomarkers"))
  .filter((b) => b.diseases.some((d) => THORACIC.includes(d)))
  .map((b) => ({
    slug: b.slug, name: b.name, gene: b.gene, summary: b.summary, biology: b.biology, alterations: b.alterations,
    testing: b.testing, predictive: b.predictiveRelevance, resistance: b.resistance, cns: b.cnsConsiderations, drugs: b.drugs,
  }));

const drugs = list(path.join(root, "content/drugs"))
  .filter((d) => d.diseases.some((x) => THORACIC.includes(x)))
  .map((d) => ({ slug: d.slug, name: d.name, brands: d.brandNames, cls: d.drugClass, targets: d.targets, mechanism: d.mechanism, toxicities: d.keyToxicities }));

trials.sort((a, b) => a.year - b.year || a.acronym.localeCompare(b.acronym));
const out = { builtOn: new Date().toISOString().slice(0, 10), trials, biomarkers, drugs };
const target = path.join(root, "simple-site/js/data.js");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(
  target,
  "// AUTO-GENERATED by scripts/build-simple-data.mjs from /content — do not edit by hand.\n" +
    "// Every number below is copied verbatim from a PubMed abstract (see each sourceQuote).\n" +
    "window.ATLAS_DATA = " + JSON.stringify(out) + ";\n",
);
console.log(`wrote ${trials.length} trials, ${biomarkers.length} biomarkers, ${drugs.length} drugs → simple-site/js/data.js`);
