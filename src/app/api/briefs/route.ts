import { NextResponse, type NextRequest } from "next/server";
import { z } from "zod";
import { assessComparability } from "@/lib/compare";
import { toVancouver } from "@/lib/citations";
import { formatEstimate, PHASE_LABEL, RESULT_LABEL } from "@/lib/utils";
import { getTrialsForCompare } from "@/server/services/trials";

export const dynamic = "force-dynamic";

const schema = z.object({
  slugs: z.string().max(2000).transform((s) => s.split(",").filter((x) => /^[a-z0-9-]+$/.test(x)).slice(0, 12)),
  title: z.string().max(200).optional(),
});

/** GET /api/briefs?slugs=a,b — structured Markdown evidence brief (sourced values only). */
export async function GET(req: NextRequest) {
  const parsed = schema.safeParse(Object.fromEntries(req.nextUrl.searchParams));
  if (!parsed.success || !parsed.data.slugs.length) return NextResponse.json({ error: "invalid_query" }, { status: 400 });
  const trials = await getTrialsForCompare(parsed.data.slugs);
  const lines: string[] = [
    `# ${parsed.data.title || "Evidence brief"}`,
    "",
    `_Generated by ONCOATLAS on ${new Date().toISOString().slice(0, 10)}. Educational; values awaiting human verification are labelled. Verify against primary sources._`,
    "",
  ];
  const warnings = assessComparability(
    trials.map((t) => ({
      acronym: t.acronym, disease: t.cancerType.shortName, setting: t.setting, lineOfTherapy: t.lineOfTherapy, stages: t.stages,
      biomarkers: t.biomarkers.map((b) => b.biomarkerSlug), comparator: t.picoComparator, phase: t.phase, randomised: t.design?.randomised,
      primaryEndpoints: t.endpoints.filter((e) => e.isPrimary).map((e) => e.code), year: t.yearOfPrimaryPublication,
    })),
  );
  if (warnings.length) lines.push("## Comparability", ...warnings.map((w) => `- **${w.level}**: ${w.message}`), "");
  const refs: string[] = [];
  for (const t of trials) {
    lines.push(`## ${t.acronym} (${t.yearOfPrimaryPublication}) — ${PHASE_LABEL[t.phase]}, ${RESULT_LABEL[t.result].toLowerCase()}`);
    lines.push(`- **Question:** ${t.clinicalQuestion}`);
    lines.push(`- **Population:** ${t.picoPopulation}`, `- **Intervention:** ${t.picoIntervention}`, `- **Comparator:** ${t.picoComparator}`);
    for (const e of t.endpoints) {
      for (const o of e.outcomes) {
        for (const a of o.analyses) {
          refs.push(toVancouver({ key: "", title: a.sourceDocument.title, journal: a.sourceDocument.journal, year: a.sourceDocument.year, firstAuthor: a.sourceDocument.firstAuthor, pmid: a.sourceDocument.pmid, doi: a.sourceDocument.doi }));
          const est = formatEstimate(a.effectMeasure, a.effectEstimate, a.ciLower, a.ciUpper, a.ciLevel);
          const vals = a.experimentalValue || a.controlValue ? `${a.experimentalValue ?? "—"} vs ${a.controlValue ?? "—"}` : "";
          lines.push(`- **${e.code}** (${o.population}, ${a.analysisLabel}): ${[vals, est, a.pValue ? `P ${a.pValue}` : ""].filter(Boolean).join("; ")} — PMID ${a.sourceDocument.pmid ?? "n/a"} [${a.status.replace(/_/g, " ").toLowerCase()}]`);
        }
      }
    }
    if (t.tumourBoardPearl) lines.push(`- **Tumour board pearl (editorial, unreviewed):** ${t.tumourBoardPearl}`);
    lines.push("");
  }
  lines.push("## References", ...[...new Set(refs)].map((r, i) => `${i + 1}. ${r}`));
  return new NextResponse(lines.join("\n"), { headers: { "Content-Type": "text/markdown; charset=utf-8" } });
}
